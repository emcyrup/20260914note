def default_questions(kind, service):
    if kind == 'guardian':
        src = GUARDIAN_JIHATSU if service == 'jihatsu' else GUARDIAN_HOUDAY
    else:
        src = STAFF_JIHATSU if service == 'jihatsu' else STAFF_HOUDAY
    return [{'no': i + 1, 'section': sec, 'text': text} for i, (sec, text) in enumerate(src)]


def questions_to_text(questions):
    """画面の編集用：区分の行は「# 区分」、設問は 1 行 1 問"""
    out, last = [], None
    for q in questions:
        if q['section'] != last:
            out.append(f'# {q["section"]}')
            last = q['section']
        out.append(q['text'])
    return '\n'.join(out)


def questions_from_text(text):
    out, section = [], ''
    for raw in (text or '').splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith('#'):
            section = line.lstrip('#').strip()[:40]
            continue
        out.append({'no': len(out) + 1, 'section': section, 'text': line[:300]})
    return out
